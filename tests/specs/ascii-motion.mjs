/** Canvas-rendered ASCII preview, custom grapheme charset, local modes and paused-frame export. */
import { pngInfo } from "../harness.mjs";
export const id = "ascii-motion";
export const title = "动态字符画";
export const gpu = "webgl2";
export async function run({ page, base, downloads, check, sleep }) {
  const res = await page.goto(`${base}/tools/ascii-motion/index.html`, { waitUntil: "networkidle2", timeout: 60000 });
  check.ok("入口可达", !!res && res.status() === 200);
  await page.waitForFunction(() => window.imagelab?.ready, { timeout: 60000 });
  await sleep(500);
  const first = await page.evaluate(() => ({ stats: window.imagelab.stats(), diag: window.imagelab.diagnostics(), canvas: document.querySelector("#ascii-holder canvas") }));
  check.ok("预览使用单张 Canvas 字符画", !!first.canvas);
  check.ok("采样格上限为 160×100", first.diag.cells <= 16000 && first.diag.cells > 0, String(first.diag.cells));
  check.ok("输出中包含字符", first.stats.chars > 1 && first.stats.count > 0, `${first.stats.rows}×${first.stats.cols}`);
  check.ok("保留四种原有 Three 场景预设", await page.evaluate(() => window.imagelab.presetCount()) === 4);
  check.ok("提供四组原有字符集预设", (await page.evaluate(() => window.imagelab.charsets())).length === 4);
  await page.select("#char-pattern", "blocks");
  check.ok("方块字符集预设同步到输入框", (await page.$eval("#charset-input", n => n.value)) === " ░▒▓█");
  await page.select("#char-pattern", "standard");
  for (const preset of ["ring", "tunnel", "wave", "jellyfish"]) {
    await page.click(`[data-preset="${preset}"]`);
    await sleep(80);
    check.ok(`Three 预设 ${preset} 可切换并渲染`, await page.evaluate(() => window.imagelab.preset()) === preset);
  }
  const motionBefore = await page.evaluate(() => window.imagelab.frame());
  await sleep(160);
  check.ok("播放状态保留真实时间动画", await page.evaluate(() => window.imagelab.frame()) > motionBefore);
  const colorBefore = await page.evaluate(() => window.imagelab.stats().avgColor.join(","));
  await page.click("#color-blue");
  await sleep(80);
  const colorAfter = await page.evaluate(() => window.imagelab.stats().avgColor.join(","));
  await page.$eval("#p-density", n => { n.value = "0.8"; n.dispatchEvent(new Event("input", { bubbles: true })); });
  check.ok("颜色控件改变字符颜色统计", colorBefore !== colorAfter, `${colorBefore} → ${colorAfter}`);
  check.ok("密度控件更新采样间距", await page.evaluate(() => window.imagelab.resolution()) > 0.15);
  await page.$eval("#charset-input", n => { n.value = "中🙂ab"; n.dispatchEvent(new Event("input", { bubbles: true })); });
  await sleep(100);
  check.ok("自定义集按字素拆分并同步下拉状态", (await page.evaluate(() => window.imagelab.charsetGlyphs())).join("") === "中🙂ab" && await page.$eval("#char-pattern", n => n.value) === "custom");
  await page.$eval("#charset-input", n => { n.value = "　".repeat(65); n.dispatchEvent(new Event("input", { bubbles: true })); });
  check.ok("空白或超过 64 字素的字符集被拒绝并保留有效集", (await page.evaluate(() => window.imagelab.charsetGlyphs())).join("") === "中🙂ab");
  await page.$eval("#charset-input", n => { n.value = "   "; n.dispatchEvent(new Event("input", { bubbles: true })); });
  check.ok("空字符集输入保留上次有效值", (await page.evaluate(() => window.imagelab.charsetGlyphs())).join("") === "中🙂ab");
  await page.click('[data-custom-mode="text"]');
  await page.$eval("#custom-text", n => { n.value = "本地字符\n图形"; n.dispatchEvent(new Event("input", { bubbles: true })); });
  await sleep(100);
  check.ok("自定义文字使用本地 Three 平面", await page.evaluate(() => window.imagelab.mode()) === "text");
  await page.click('[data-motion="rotate"]');
  check.ok("动效选项可切换", await page.evaluate(() => window.imagelab.motion()) === "rotate");
  await page.click('[data-custom-mode="image"]');
  await page.evaluate(async () => {
    const c = document.createElement("canvas"); c.width = 96; c.height = 48;
    const x = c.getContext("2d"); x.fillStyle = "#000"; x.fillRect(28, 10, 40, 28);
    const blob = await new Promise(resolve => c.toBlob(resolve, "image/png"));
    const input = document.querySelector("#custom-image-file"), data = new DataTransfer();
    data.items.add(new File([blob], "transparent-logo.png", { type: "image/png" }));
    input.files = data.files; input.dispatchEvent(new Event("change", { bubbles: true }));
  });
  await page.waitForFunction(() => window.imagelab.hasImage() && window.imagelab.diagnostics().alphaMode);
  check.ok("透明 Logo 自动按 alpha 轮廓采样", await page.evaluate(() => window.imagelab.diagnostics().alphaMode));
  await page.click('[data-custom-mode="scene"]');
  check.ok("切回 Three 场景后不沿用图片 alpha 规则", !(await page.evaluate(() => window.imagelab.diagnostics().alphaMode)));
  await page.click("#btn-pause");
  await sleep(120);
  const frame = await page.evaluate(() => ({ t: window.imagelab.frame(), renders: window.imagelab.diagnostics().renderCount }));
  await sleep(200);
  const still = await page.evaluate(() => ({ t: window.imagelab.frame(), renders: window.imagelab.diagnostics().renderCount }));
  check.ok("暂停后不再调度渲染", frame.t === still.t && frame.renders === still.renders);
  await page.$eval("#p-glow", n => { n.value = "0"; n.dispatchEvent(new Event("input", { bubbles: true })); });
  const noGlow = await page.evaluate(() => window.imagelab.exportDataURL());
  await page.$eval("#p-glow", n => { n.value = "1"; n.dispatchEvent(new Event("input", { bubbles: true })); });
  const fullGlow = await page.evaluate(() => window.imagelab.exportDataURL());
  check.ok("辉光强度 0 与 1 产生不同的同画布像素", noGlow !== fullGlow);
  const size = await page.evaluate(() => window.imagelab.exportSize());
  const url = await page.evaluate(() => window.imagelab.exportDataURL());
  const exported = await page.evaluate(async data => { const i = new Image(); i.src = data; await i.decode(); return [i.naturalWidth, i.naturalHeight]; }, url);
  check.ok("导出与预览同一张画布", exported[0] === size.width && exported[1] === size.height);
  await page.click("#btn-export");
  const file = await downloads.waitForFile({ ext: ".png", timeoutMs: 30000 });
  const info = pngInfo(file.bytes);
  check.ok("下载 PNG 有效", info.width === size.width && info.height === size.height && file.size > 1000);
}
